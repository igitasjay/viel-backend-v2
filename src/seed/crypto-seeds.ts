const getNextId = async (): Promise<number> => {
  const counter = await Counter.findOneAndUpdate(
    { _id: 'cryptoAssetId' },
    { $inc: { seq: 1 } },
    { upsert: true, new: true },
  );
  return counter.seq;
};

// === SEED ===
const seedCryptoAssets = async () => {
  try {
    await connectToDatabase(); // Only once

    for (const asset of seedData) {
      const existing = await CryptoAsset.findOne({ code: asset.code });
      if (!existing) {
        const nextId = await getNextId();
        await CryptoAsset.create({ ...asset, id: nextId });
        logger.info(`Created: ${asset.code} (id: ${nextId})`);
      } else {
        await CryptoAsset.updateOne({ _id: existing._id }, { $set: asset });
        logger.info(`Updated: ${asset.code} (id: ${existing.id})`);
      }
    }

    logger.info('Crypto assets seeded successfully.');
    process.exit(0);
  } catch (error) {
    logger.error('Seeding failed:', error);
    process.exit(1);
  }
};

seedCryptoAssets();
